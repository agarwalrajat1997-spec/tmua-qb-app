import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
import * as questionModule from '../lib/ib/question.ts';
const {IB_COLLECTIONS,ibQuestionSchema}=questionModule.default??questionModule;
import * as indexModule from '../lib/ib/build-content-index.ts';
const {buildIbContentIndex}=indexModule.default??indexModule;
const source=IB_COLLECTIONS.map(c=>({id:c.id,path:`@/content/ib/${c.subject}/${c.subject==='math-aa-hl'?c.id:c.topicId}.json`}));
// Preserve frozen legacy banks. Each new topic has its own small server chunk.
const additions=[
 ...['aa-sl','aa-hl','ai-sl','ai-hl'].flatMap(course=>JSON.parse(readFileSync(`content/ib/math-2026-expansion/${course}.json`,'utf8'))),
 ...['structure','periodicity','reactivity','mechanisms'].flatMap(batch=>JSON.parse(readFileSync(`content/ib/chemistry-2026-expansion/${batch}.json`,'utf8'))),
 ...['unity-diversity','form-function','interaction-interdependence','continuity-change'].flatMap(batch=>JSON.parse(readFileSync(`content/ib/biology-2026-expansion/${batch}.json`,'utf8'))),
].map(q=>ibQuestionSchema.parse(q));
const chemistryPractice=['s1','s2','s3','r1','r2','r3'].flatMap(theme=>JSON.parse(readFileSync(`content/ib/chemistry-2025-practice/${theme}.json`,'utf8'))).map(q=>ibQuestionSchema.parse(q));
for(const s of source){
 const items=additions.filter(q=>q.collectionId===s.id);
 if(!items.length)continue;
 const derived=`content/ib/${items[0].subject==='chemistry'?'chemistry':items[0].subject==='biology'?'biology':'math'}-2026-expansion/by-collection`;
 if(!process.argv.includes('--check'))mkdirSync(derived,{recursive:true});
 s.additionPath=`@/${derived}/${s.id}.json`;
 const expected=JSON.stringify(items)+'\n';
 if(process.argv.includes('--check'))assert.equal(readFileSync(s.additionPath.slice(2),'utf8'),expected,'Stale enrichment bank '+s.id);
 else writeFileSync(s.additionPath.slice(2),expected);
}
for(const s of source.filter(s=>s.id.startsWith('chemistry-'))){
 const theme=s.id.replace('chemistry-structure-','s').replace('chemistry-reactivity-','r');
 s.practicePath=`@/content/ib/chemistry-2025-practice/${theme}.json`;
}
const fiscalPath='@/content/ib/syllabus-updates-2026/economics-macroeconomics.json';
const fiscal=JSON.parse(readFileSync(fiscalPath.slice(2),'utf8')).map(q=>ibQuestionSchema.parse(q));
const functionsPractice=[];
for(const [id,course,count] of [['aa-sl-functions','sl',60],['functions','hl',100]]){
 const path='@/content/ib/aa-functions-practice/'+course+'.json';
 const rows=JSON.parse(readFileSync(path.slice(2),'utf8')).map(q=>ibQuestionSchema.parse(q));
 assert.equal(rows.length,count);
 assert.ok(rows.every(q=>q.collectionId===id&&q.subject==='math-aa-'+course&&q.status==='published'));
 source.find(s=>s.id===id).practicePath=path;
 functionsPractice.push(...rows);
}
const assessmentPractice=[];
for(const id of ['aa-sl-statistics-probability','aa-sl-calculus','statistics-probability','geometry-trigonometry','number-algebra','calculus-1','calculus-2']){
 const spec=source.find(s=>s.id===id);
 const path='@/content/ib/practice-2027/banks/'+id+'.json';
 const rows=JSON.parse(readFileSync(path.slice(2),'utf8')).map(q=>ibQuestionSchema.parse(q));
 assert.ok(rows.length && rows.every(q=>q.collectionId===id && q.status==='published'));
 spec.practicePath=path;
 assessmentPractice.push(...rows);
}
const questions=[...assessmentPractice,...source.flatMap(s=>JSON.parse(readFileSync(s.path.slice(2),'utf8')).map(q=>ibQuestionSchema.parse(q))),...additions,...chemistryPractice,...fiscal,...functionsPractice];
const index=JSON.stringify(buildIbContentIndex(questions))+'\n';
const loaders='// Generated by scripts/generate-ib-content-index.mjs. Explicit imports keep banks in separate server chunks.\nexport const IB_BANK_LOADERS = {\n'+source.map(s=>s.id==='economics-macroeconomics'
 ? '  '+JSON.stringify(s.id)+': async () => { const [bank, fiscal] = await Promise.all([import('+JSON.stringify(s.path)+'), import('+JSON.stringify(fiscalPath)+')]); return { default: [...bank.default, ...fiscal.default] }; },'
 : s.practicePath
 ? `  ${JSON.stringify(s.id)}: async () => { const [bank, additions, practice] = await Promise.all([import(${JSON.stringify(s.path)}), import(${JSON.stringify(s.additionPath)}), import(${JSON.stringify(s.practicePath)})]); return { default: [...bank.default, ...additions.default, ...practice.default] }; },`
 : s.additionPath
 ? `  ${JSON.stringify(s.id)}: async () => { const [bank, additions] = await Promise.all([import(${JSON.stringify(s.path)}), import(${JSON.stringify(s.additionPath)})]); return { default: [...bank.default, ...additions.default] }; },`
 : `  ${JSON.stringify(s.id)}: () => import(${JSON.stringify(s.path)}),`).join('\n')+'\n};\n';
for(const [path,expected] of [['content/ib/content-index.json',index],['lib/ib/bank-loaders.ts',loaders]]){
 if(process.argv.includes('--check'))assert.equal(readFileSync(path,'utf8'),expected,`${path} is stale: npm run generate:ib-content-index`);
 else writeFileSync(path,expected);
}
console.log(`IB navigation index ${process.argv.includes('--check')?'verified':'generated'}: ${questions.length} questions, ${source.length} independent banks, ${Buffer.byteLength(index)} metadata bytes; no question/answer bodies.`);
